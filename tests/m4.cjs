const { chromium } = require('playwright');
(async () => {
  const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
  const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
  const errs = [];
  page.on('console', (m) => { if (m.type() === 'error') errs.push('console: ' + m.text()); });
  page.on('pageerror', (e) => errs.push('PAGEERROR: ' + e.message));
  await page.goto('http://127.0.0.1:5173/');
  await page.evaluate(() => localStorage.setItem('geocraft.settings.v1', JSON.stringify({ helpSeen: true, platform: 'pc' })));
  await page.reload();
  await page.waitForTimeout(3500);
  await page.click('text=Jouer');
  await page.waitForTimeout(2500);
  await page.evaluate(() => { const g = __geo; g.sky.frozen = true; g.sky.time = 0.25; g.player.teleport(10.5, 47.2, 11.8); g.player.yaw = 0; g.player.pitch = -0.1; });
  await page.waitForTimeout(1500);
  await page.screenshot({ path: 'tests/out/m4-prof.png' });
  await page.keyboard.press('f');
  await page.waitForTimeout(600);
  console.log('boutique ouverte', await page.evaluate(() => __geo.screens.open + ' ' + __geo.screens.tab));
  await page.evaluate(() => { const g = __geo; g.inv.add('b_log', 20); g.inv.add('b_dirt', 30); g.inv.add('b_stone', 40); g.inv.add('res_cuivre', 10); g.inv.add('res_fer', 10); g.inv.add('res_or', 5); });
  await page.waitForTimeout(300);
  await page.screenshot({ path: 'tests/out/m4-shop.png' });
  const offers = page.locator('.offer');
  console.log('offres', await offers.count());
  await offers.nth(0).click();
  await page.waitForTimeout(200);
  console.log('inventaire', await page.evaluate(() => JSON.stringify(__geo.inv.slots.filter(Boolean).map((s) => s.id + 'x' + s.n))));
  await page.click('text=Améliorer');
  await page.waitForTimeout(300);
  await page.screenshot({ path: 'tests/out/m4-upgrade.png' });
  const ups = page.locator('.offer');
  console.log('améliorations', await ups.count());
  if ((await ups.count()) > 0) await ups.nth(0).click();
  await page.waitForTimeout(200);
  console.log('inventaire après amélioration', await page.evaluate(() => JSON.stringify(__geo.inv.slots.filter(Boolean).map((s) => s.id + 'x' + s.n))));
  await page.keyboard.press('Escape');
  await page.waitForTimeout(500);
  console.log('fermée', await page.evaluate(() => !__geo.screens.open));
  await page.keyboard.press('c');
  await page.waitForTimeout(500);
  await page.screenshot({ path: 'tests/out/m4-craft.png' });
  const rec = page.locator('.offer');
  console.log('recettes', await rec.count());
  await rec.nth(0).click();
  await page.waitForTimeout(200);
  console.log('planches', await page.evaluate(() => __geo.inv.count('b_planks')));
  console.log('erreurs:', errs.length ? errs.join('\n') : 'aucune');
  await browser.close();
})();
